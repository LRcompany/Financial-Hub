import "dotenv/config";
import express from "express";
import cors from "cors";
import { transactionsRouter } from "./src/routes/transactions.js";
import { categoriesRouter } from "./src/routes/categories.js";
import { budgetRouter } from "./src/routes/budget.js";
import { wealthRouter } from "./src/routes/wealth.js";
import { wealthGoalRouter } from "./src/routes/wealthGoal.js";
import { positionsRouter } from "./src/routes/positions.js";
import { projectsRouter } from "./src/routes/projects.js";
import { brokersRouter } from "./src/routes/brokers.js";
import { contributionsRouter } from "./src/routes/contributions.js";
import { dataHealthRouter } from "./src/routes/dataHealth.js";
const app = express();
app.use(cors({ origin: true, credentials: true }));
app.use(express.json());
app.get("/api/auth/status", (_req, res) => res.json({ authenticated: true, hasPinConfigured: true }));
for (const r of [transactionsRouter, categoriesRouter, budgetRouter, wealthRouter, wealthGoalRouter, positionsRouter, projectsRouter, brokersRouter, contributionsRouter, dataHealthRouter]) app.use("/api", r);
app.listen(3334, () => console.log("ok"));
